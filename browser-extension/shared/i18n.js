export function t(key, locale = 'de-DE') {
    return STRINGS[locale]?.[key] || STRINGS['en-US']?.[key] || key;
}

export function applyI18n(root, locale) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key, locale);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'), locale);
    });
}
